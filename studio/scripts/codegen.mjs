// The page's types, generated from the JSON Schemas the Python side writes: one definition for both sides.
// Run after `uv run python -m policyproof.studio.schema`.
import { readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const here = new URL("..", import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, here), "utf8"));
const banner = "/* Generated by scripts/codegen.mjs from the Python side's JSON Schema. Do not edit. */";

// Property titles would become needless named types; the definitions' own titles name the interfaces. The keys of
// `properties` and `$defs` are names, not keywords, so a property called `title` stays.
function untitled(node) {
  if (Array.isArray(node)) return node.map(untitled);
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "title") continue;
    out[k] = k === "properties" || k === "$defs" ? Object.fromEntries(Object.entries(v).map(([n, x]) => [n, untitled(x)]))
      : untitled(v);
  }
  return out;
}

function defsTitled(schema) {
  const out = untitled(schema);
  for (const name of Object.keys(out.$defs ?? {})) out.$defs[name].title = name;
  return out;
}

const options = { bannerComment: banner, additionalProperties: false, unreachableDefinitions: true, format: true };
const api = read("../src/policyproof/studio/api.schema.json");
writeFileSync(new URL("src/gen/api.schema.json", here), JSON.stringify(api, null, 2) + "\n");
writeFileSync(new URL("src/gen/api.ts", here), await compile(defsTitled(api), "Api", options));
const policy = read("../src/policyproof/schema/policy.schema.json");
writeFileSync(new URL("src/gen/policy.ts", here), await compile(defsTitled(policy), "Policy", options));
